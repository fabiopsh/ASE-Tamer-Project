#!/bin/sh
# Generates the local CA, one TLS certificate per container, the JWT key pair, database
# passwords and service client secrets into /secrets (a named volume). Runs only once: if
# /secrets/.done exists nothing is changed. Remove the volume to regenerate everything.
#
# Layout: see docs/plan/02-infrastructure.md (INFRA-4). Every container mounts only its own
# sub-directory (compose volume subpath), so a file is visible only where it is needed.
set -eu
umask 022

OUT=/secrets
SERVICES="auth players monsters teams encounters history"
# Clients that auth accepts on the client credentials grant ("tests" only with the test override)
CALLERS="players teams encounters tests"
CA_DAYS=3650
CERT_DAYS=825

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

random_secret() {
    openssl rand -hex 32
}

# issue_cert <dir> <common name> <subjectAltName>
issue_cert() {
    dir="$1"; cn="$2"; san="$3"
    mkdir -p "$OUT/$dir/tls"
    openssl req -new -newkey rsa:2048 -nodes -subj "/CN=$cn" \
        -keyout "$OUT/$dir/tls/server.key" -out "$TMP/$dir.csr" 2>/dev/null
    cat > "$TMP/$dir.ext" <<EXT
basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature,keyEncipherment
extendedKeyUsage=serverAuth,clientAuth
subjectAltName=$san
EXT
    openssl x509 -req -in "$TMP/$dir.csr" -CA "$OUT/ca/ca.crt" -CAkey "$OUT/ca/ca.key" \
        -set_serial "0x$(openssl rand -hex 16)" -days "$CERT_DAYS" -sha256 \
        -extfile "$TMP/$dir.ext" -out "$OUT/$dir/tls/server.crt" 2>/dev/null
    cp "$OUT/ca/ca.crt" "$OUT/$dir/ca.crt"
}

if [ -f "$OUT/.done" ]; then
    # Volumes created before the frontend container existed: add only its certificate.
    if [ ! -f "$OUT/frontend/tls/server.crt" ]; then
        echo "init-secrets: adding the frontend certificate"
        issue_cert frontend frontend "DNS:frontend,DNS:localhost,IP:127.0.0.1"
        chmod 0755 "$OUT/frontend" "$OUT/frontend/tls"
        chmod 0644 "$OUT/frontend/ca.crt" "$OUT/frontend/tls/server.crt" "$OUT/frontend/tls/server.key"
    fi
    echo "init-secrets: secrets already present, nothing to do"
    exit 0
fi

# A previous run may have stopped half-way: start from an empty volume.
find "$OUT" -mindepth 1 -delete

echo "init-secrets: generating local CA"
mkdir -p "$OUT/ca"
openssl req -x509 -new -newkey rsa:4096 -nodes -sha256 -days "$CA_DAYS" \
    -subj "/CN=Monster Tamers Local CA" \
    -addext "basicConstraints=critical,CA:TRUE" \
    -addext "keyUsage=critical,keyCertSign,cRLSign" \
    -keyout "$OUT/ca/ca.key" -out "$OUT/ca/ca.crt" 2>/dev/null

echo "init-secrets: generating JWT key pair"
openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$TMP/jwt-private.pem" 2>/dev/null
openssl pkey -in "$TMP/jwt-private.pem" -pubout -out "$TMP/jwt-public.pem"

echo "init-secrets: gateway certificate"
issue_cert gateway localhost "DNS:localhost,IP:127.0.0.1,DNS:gateway"

echo "init-secrets: frontend certificate"
issue_cert frontend frontend "DNS:frontend,DNS:localhost,IP:127.0.0.1"

# Client secrets are generated first because auth needs all of them.
for client in $SERVICES tests; do
    random_secret > "$TMP/client-$client"
done

for svc in $SERVICES; do
    echo "init-secrets: $svc"
    issue_cert "$svc" "$svc" "DNS:$svc,DNS:localhost,IP:127.0.0.1"
    issue_cert "$svc-db" "$svc-db" "DNS:$svc-db"
    cp "$TMP/jwt-public.pem" "$OUT/$svc/jwt-public.pem"

    db_password=$(random_secret)
    printf '%s' "$db_password" > "$OUT/$svc-db/db-password"

    {
        echo "# Generated by init-secrets. Do not edit, do not copy outside the container."
        # Higher than application.properties (250), lower than environment variables (300)
        echo "config_ordinal=270"
        echo "quarkus.datasource.password=$db_password"
        echo "tamer.service-client.id=$svc"
        echo "tamer.service-client.secret=$(cat "$TMP/client-$svc")"
    } > "$OUT/$svc/secrets.properties"
done

cp "$TMP/jwt-private.pem" "$OUT/auth/jwt-private.pem"
for client in $CALLERS; do
    echo "tamer.service-clients.$client=$(cat "$TMP/client-$client")" >> "$OUT/auth/secrets.properties"
done

# Used only by the component tests through the test override (TEST-1)
mkdir -p "$OUT/tests"
cp "$OUT/ca/ca.crt" "$OUT/tests/ca.crt"
{
    echo "TAMER_TEST_CLIENT_ID=tests"
    echo "TAMER_TEST_CLIENT_SECRET=$(cat "$TMP/client-tests")"
} > "$OUT/tests/client.env"

# Readable by the (different) non-root users of the other containers; isolation comes from
# the subpath mounts. ca/ca.key is never mounted anywhere.
find "$OUT" -type d -exec chmod 0755 {} +
find "$OUT" -type f -exec chmod 0644 {} +
chmod 0700 "$OUT/ca"
chmod 0600 "$OUT/ca/ca.key"

touch "$OUT/.done"
echo "init-secrets: done"
