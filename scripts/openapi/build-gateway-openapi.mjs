// Builds docs/openapi/gateway.yaml: the public API as seen through the Nginx gateway (DOC-1/DOC-2).
// - drops /internal/* and /q/* paths (the gateway answers 404 for them) and internal tags;
// - merges the six service specs, prefixing schema names with the service so names never collide;
// - prunes schemas not transitively referenced by any public path (no internal schemas leak);
// - one server: https://localhost:8443.
// Run after the service specs are in docs/openapi/<svc>.yaml (scripts/export-openapi.sh does both).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, '..', '..', 'docs', 'openapi');
const services = ['auth', 'players', 'monsters', 'teams', 'encounters', 'history'];
const prefix = (svc) => svc[0].toUpperCase() + svc.slice(1) + '_';

const gateway = {
  openapi: '3.1.0',
  info: {
    title: 'Monster Tamers - gateway',
    version: '1.0.0',
    description:
      'Public API of Monster Tamers through the Nginx gateway. Authenticate with POST /api/auth/token ' +
      '(OAuth2 password or refresh_token grant, form-urlencoded, 300 s RS256 access tokens) and revoke ' +
      'sessions with POST /api/auth/logout. Protected routes are authorized at the gateway (auth_request) ' +
      'and independently in each service using the canonical access-policy.json table. Monster sprites ' +
      '(/images/monsters/*) are public; internal endpoints are never exposed. ' +
      'Generated by scripts/openapi/build-gateway-openapi.mjs from the service specs.',
  },
  servers: [{ url: 'https://localhost:8443', description: 'Gateway (local CA certificate, see README)' }],
  tags: [],
  paths: {},
  components: {
    schemas: {},
    securitySchemes: {
      bearerAuth: {
        type: 'http',
        scheme: 'bearer',
        bearerFormat: 'JWT',
        description: 'Player access token from POST /api/auth/token',
      },
    },
  },
};

const allSchemas = {};

for (const svc of services) {
  const spec = YAML.parse(fs.readFileSync(path.join(dir, `${svc}.yaml`), 'utf8'));
  const rename = new Map(Object.keys(spec.components?.schemas ?? {}).map((n) => [n, prefix(svc) + n]));
  const fix = (node) => {
    if (Array.isArray(node)) return node.map(fix);
    if (node && typeof node === 'object') {
      const out = {};
      for (const [k, v] of Object.entries(node)) {
        if (k === '$ref' && typeof v === 'string' && v.startsWith('#/components/schemas/')) {
          const name = v.slice('#/components/schemas/'.length);
          out[k] = '#/components/schemas/' + (rename.get(name) ?? name);
        } else {
          out[k] = fix(v);
        }
      }
      return out;
    }
    return node;
  };
  for (const [p, item] of Object.entries(spec.paths ?? {})) {
    if (p.startsWith('/internal/') || p.startsWith('/q/')) continue;
    if (gateway.paths[p]) throw new Error(`Path ${p} defined by two services`);
    gateway.paths[p] = fix(item);
  }
  for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
    allSchemas[rename.get(name)] = fix(schema);
  }
  for (const tag of spec.tags ?? []) {
    if (!tag.name.endsWith('-internal')) gateway.tags.push(tag);
  }
  for (const name of Object.keys(spec.components?.securitySchemes ?? {})) {
    if (name !== 'bearerAuth') gateway.components.securitySchemes[name] = spec.components.securitySchemes[name];
  }
}

// Keep only schemas transitively referenced from public paths (never leak internal request/response DTOs)
const collectRefs = (node, out) => {
  if (Array.isArray(node)) {
    for (const item of node) collectRefs(item, out);
  } else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      if (k === '$ref' && typeof v === 'string' && v.startsWith('#/components/schemas/')) {
        out.add(v.slice('#/components/schemas/'.length));
      } else {
        collectRefs(v, out);
      }
    }
  }
};

const referenced = new Set();
const queue = [];
collectRefs(gateway.paths, referenced);
for (const name of referenced) queue.push(name);
while (queue.length > 0) {
  const name = queue.pop();
  const schema = allSchemas[name];
  if (!schema) continue;
  const nested = new Set();
  collectRefs(schema, nested);
  for (const n of nested) {
    if (!referenced.has(n)) {
      referenced.add(n);
      queue.push(n);
    }
  }
}
for (const name of [...referenced].sort()) {
  if (allSchemas[name]) gateway.components.schemas[name] = allSchemas[name];
}

// Keep only tags used by at least one public operation
const used = new Set(
  Object.values(gateway.paths).flatMap((item) => Object.values(item).flatMap((op) => op?.tags ?? [])),
);
gateway.tags = gateway.tags.filter((t) => used.has(t.name));
if (gateway.tags.length === 0) delete gateway.tags;

fs.writeFileSync(path.join(dir, 'gateway.yaml'), YAML.stringify(gateway, { lineWidth: 0 }));
console.log(
  `docs/openapi/gateway.yaml: ${Object.keys(gateway.paths).length} paths, ` +
    `${Object.keys(gateway.components.schemas).length} schemas`,
);
