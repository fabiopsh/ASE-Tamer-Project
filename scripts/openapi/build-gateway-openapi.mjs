// Builds docs/openapi/gateway.yaml: the public API as seen through the Nginx gateway (DOC-1).
// - drops /internal/* paths (the gateway answers 404 for them) and the internal tags;
// - merges the six service specs; schema names are prefixed with the service (Teams_TeamResponse)
//   so that equal names from different services do not collide;
// - one server: https://localhost:8443.
// Run after the service specs are in docs/openapi/<svc>.yaml (scripts/export-openapi.sh does both).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, '..', '..', 'docs', 'openapi');
const services = ['auth', 'players', 'monsters', 'teams', 'encounters', 'history'];
const prefix = (svc) => svc[0].toUpperCase() + svc.slice(1) + '_';

const gateway = {
  openapi: '3.1.0',
  info: {
    title: 'Monster Tamers - gateway',
    version: '0.1.0',
    description:
      'Public API of Monster Tamers through the Nginx gateway. Log in with POST /api/auth/token ' +
      '(OAuth2 password grant, form-urlencoded) and send the access token as Authorization: Bearer. ' +
      'Monster sprites (/images/monsters/*) are public. Internal endpoints are not exposed. ' +
      'Generated by scripts/openapi/build-gateway-openapi.mjs from the service specs.',
  },
  servers: [{ url: 'https://localhost:8443', description: 'Gateway (local CA certificate, see README)' }],
  tags: [],
  paths: {},
  components: {
    schemas: {},
    securitySchemes: {
      bearerAuth: {
        type: 'http',
        scheme: 'bearer',
        bearerFormat: 'JWT',
        description: 'Player access token from POST /api/auth/token',
      },
    },
  },
};

for (const svc of services) {
  const spec = YAML.parse(fs.readFileSync(path.join(dir, `${svc}.yaml`), 'utf8'));
  const rename = new Map(Object.keys(spec.components?.schemas ?? {}).map((n) => [n, prefix(svc) + n]));
  // Rewrites every $ref to a schema of this service
  const fix = (node) => {
    if (Array.isArray(node)) return node.map(fix);
    if (node && typeof node === 'object') {
      const out = {};
      for (const [k, v] of Object.entries(node)) {
        if (k === '$ref' && typeof v === 'string' && v.startsWith('#/components/schemas/')) {
          const name = v.slice('#/components/schemas/'.length);
          out[k] = '#/components/schemas/' + (rename.get(name) ?? name);
        } else {
          out[k] = fix(v);
        }
      }
      return out;
    }
    return node;
  };
  for (const [p, item] of Object.entries(spec.paths ?? {})) {
    if (p.startsWith('/internal/') || p.startsWith('/q/')) continue;
    if (gateway.paths[p]) throw new Error(`Path ${p} defined by two services`);
    gateway.paths[p] = fix(item);
  }
  for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
    gateway.components.schemas[rename.get(name)] = fix(schema);
  }
  for (const tag of spec.tags ?? []) {
    if (!tag.name.endsWith('-internal')) gateway.tags.push(tag);
  }
  // Operations that use the service's own scheme name keep working with the gateway's bearerAuth
  for (const name of Object.keys(spec.components?.securitySchemes ?? {})) {
    if (name !== 'bearerAuth') gateway.components.securitySchemes[name] = spec.components.securitySchemes[name];
  }
}

// Keep only tags used by at least one public operation
const used = new Set(
  Object.values(gateway.paths).flatMap((item) => Object.values(item).flatMap((op) => op?.tags ?? [])),
);
gateway.tags = gateway.tags.filter((t) => used.has(t.name));
if (gateway.tags.length === 0) delete gateway.tags;

fs.writeFileSync(path.join(dir, 'gateway.yaml'), YAML.stringify(gateway, { lineWidth: 0 }));
console.log(`docs/openapi/gateway.yaml: ${Object.keys(gateway.paths).length} paths, ` +
  `${Object.keys(gateway.components.schemas).length} schemas`);
